const { chromium } = require('@playwright/test');
const assert = require('node:assert/strict');
let browser;
(async () => {
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(process.env.BASE_URL || 'http://localhost:5173');
  await page.locator('#go-intro').waitFor({ state: 'detached' });
  await page.getByText('Build muscle', { exact: true }).click();
  const open = () => page.getByRole('button', { name: 'Create your own avatar?', exact: true }).click();
  await open();
  const dialog = page.getByRole('dialog');
  assert.equal(await dialog.getByRole('button', { name: 'Use this avatar' }).isDisabled(), true);
  await dialog.getByLabel('Upload avatar photo').setInputFiles({ name: 'bad.txt', mimeType: 'text/plain', buffer: Buffer.from('bad') });
  assert.match(await dialog.getByRole('alert').textContent(), /Choose a JPG/);
  await dialog.getByLabel('Upload avatar photo').setInputFiles({ name: 'broken.png', mimeType: 'image/png', buffer: Buffer.from('broken') });
  await dialog.getByRole('alert').filter({ hasText: 'couldn’t open' }).waitFor();
  await dialog.getByLabel('Upload avatar photo').setInputFiles('public/cat-coach/portrait.png');
  await dialog.locator('canvas').waitFor();
  const first = await dialog.locator('canvas').evaluate(c => c.toDataURL());
  await dialog.getByLabel('Zoom', { exact: true }).fill('1.5');
  await dialog.getByLabel('Vertical position', { exact: true }).fill('25');
  assert.notEqual(await dialog.locator('canvas').evaluate(c => c.toDataURL()), first);
  await page.screenshot({path:'/tmp/go-avatar-editor.png',fullPage:true});
  await dialog.getByRole('button', { name: 'Use this avatar' }).click();
  const avatar = await page.locator('.wizard-avatar-trigger img').getAttribute('src');
  assert.match(avatar, /^data:image\/jpeg;base64,/);
  assert(avatar.length < 150000, 'avatar should remain small enough for local profile storage');
  await page.getByRole('button', { name: /^Male/ }).click();
  assert.equal(await page.locator('.body-choices svg image').count(), 3);
  for (const image of await page.locator('.body-choices svg image').all()) assert.equal(await image.getAttribute('href'), avatar);
  await page.screenshot({path:'/tmp/go-avatar-body-types.png',fullPage:true});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  await page.getByRole('button', { name: 'Back', exact: true }).click();
  await page.getByRole('button', { name: 'Edit your avatar', exact: true }).click();
  await dialog.getByRole('button', { name: 'Cancel', exact: true }).click();
  assert.equal(await page.locator('.wizard-avatar-trigger img').getAttribute('src'), avatar);
  await page.getByRole('button', { name: /^Female/ }).click();
  await page.getByRole('button', { name: /^Athletic/ }).click();
  assert.equal(await page.getByAltText('Your custom avatar').getAttribute('src'), avatar);
  await page.getByRole('button', { name: 'Save your profile and go to training', exact: true }).click();
  assert.equal(await page.locator('nav [aria-current="page"]').textContent(), 'Training');
  await page.reload();
  await page.locator('#go-intro').waitFor({ state: 'detached' });
  await page.getByText('Build muscle', { exact: true }).click();
  assert.equal(await page.locator('.wizard-avatar-trigger img').getAttribute('src'), avatar);
  await page.getByRole('button', { name: 'Remove avatar', exact: true }).click();
  assert.equal(await page.locator('.gender-choices svg image').count(), 0);
  await open();
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(), 0);
  assert.deepEqual(errors, []);
  console.log('PASS avatar upload errors, crop controls, photo-to-character integration, back/cancel, mobile layout, save/reload, removal and Escape');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { await browser?.close(); });
