const { chromium } = require('@playwright/test');
const assert = require('node:assert/strict');
let browser;
(async () => {
  browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || '/usr/bin/chromium', args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 390, height: 844 }, reducedMotion: 'reduce' });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(process.env.BASE_URL || 'http://localhost:5173');
  await page.locator('#go-intro').waitFor({ state: 'detached' });
  await page.getByText('Build muscle', { exact: true }).click();
  assert.equal(await page.getByRole('button', {name:'Create your own avatar?',exact:true}).count(),0);
  await page.getByRole('button',{name:/Select your avatar/}).click();
  const picker = page.getByRole('dialog',{name:'Select your avatar',exact:true});
  const checkPlainPicker = async () => {
    assert.equal(await picker.locator('.animal-avatar[data-muscle-details="off"]').count(),2, 'both picker characters use a plain body preview');
    assert.equal(await picker.locator('img.animal-avatar-uploaded').count(),0, 'the supplied Lean image does not replace plain picker characters');
    assert.equal(await picker.locator('.animal-muscle-contours, .animal-limb-contours, .animal-pectoral-contours').count(),0, 'picker characters have no chest, abdomen or limb muscle lines');
  };
  const checkBuildMuscles = async () => {
    assert.equal(await page.locator('.body-choices .animal-avatar[data-muscle-details="on"]').count(),3, 'body-type previews retain build definition');
    assert.equal(await page.locator('.body-choices [data-build="lean"] .animal-pectoral-contours').count(),0, 'Lean remains free of added chest definition');
    for (const build of ['athletic','strong']) {
      const pectorals = page.locator(`.body-choices [data-build="${build}"] .animal-pectoral-contours`);
      assert.equal(await pectorals.count(),1, `${build} restores chest definition`);
      assert(await pectorals.locator('path').count() >= 2, `${build} renders the paired chest contours`);
    }
  };
  const checkMaleLeanImage = async (scope) => {
    const image = scope.locator('img.animal-avatar[data-species="shiba"][data-gender="male"][data-build="lean"]');
    assert.equal(await image.count(),1, 'only Male Shiba Lean uses the supplied image');
    assert.equal(await image.getAttribute('src'),'/avatars/male-dog-lean.png');
    const details = await image.evaluate(async image => {
      await image.decode();
      return {width:image.naturalWidth,height:image.naturalHeight,fit:getComputedStyle(image).objectFit};
    });
    assert.equal(details.width,1024);
    assert.equal(details.height,1536);
    assert.equal(details.fit,'contain', 'the entire supplied composition is preserved');
  };
  await checkPlainPicker();
  assert.equal(await picker.locator('.animal-avatar').count(),2);
  assert.equal(await picker.locator('input[type="file"], svg image').count(),0);
  await picker.getByRole('button',{name:'Select Selkirk Rex',exact:true}).click();
  await picker.getByRole('button',{name:'Use this avatar',exact:true}).click();
  await page.getByRole('button',{name:/^Male/}).click();
  assert.equal(await page.locator('.body-choices .animal-avatar[data-species="selkirk"]').count(),3);
  assert.deepEqual(await page.locator('.body-choices .animal-avatar').evaluateAll(es=>es.map(e=>e.dataset.build)),['lean','athletic','strong']);
  await checkBuildMuscles();
  const torsoWidths = await page.locator('.body-choices .animal-torso').evaluateAll(es=>es.map(e=>e.getBBox().width));
  assert(torsoWidths[1] > torsoWidths[0] * 1.2, 'athletic silhouette should be visibly wider than lean');
  assert(torsoWidths[2] > torsoWidths[1] * 1.2, 'strong silhouette should be visibly wider than athletic');
  assert.equal(await page.locator('.body-choices .animal-avatar[data-gender="male"]').count(),3);
  const malePaths = await page.locator('.body-choices .animal-torso').evaluateAll(es=>es.map(e=>e.getAttribute('d')));
  const maleProportions = await page.locator('.body-choices .animal-body').evaluateAll(es=>es.map(e=>({waist:Number(e.dataset.waistWidth),hip:Number(e.dataset.hipWidth)})));
  await page.getByRole('button',{name:'Step 2: About you',exact:true}).click();
  await page.getByRole('button',{name:/^Female/}).click();
  assert.equal(await page.locator('.body-choices .animal-avatar[data-gender="female"]').count(),3);
  await checkBuildMuscles();
  const femalePaths = await page.locator('.body-choices .animal-torso').evaluateAll(es=>es.map(e=>e.getAttribute('d')));
  const femaleProportions = await page.locator('.body-choices .animal-body').evaluateAll(es=>es.map(e=>({waist:Number(e.dataset.waistWidth),hip:Number(e.dataset.hipWidth)})));
  femalePaths.forEach((path,index)=>assert.notEqual(path,malePaths[index], 'gender changes the actual body silhouette for every build'));
  femaleProportions.forEach((shape,index)=>{
    assert(shape.waist < maleProportions[index].waist, 'female waist is narrower for the same build');
    assert(shape.hip > maleProportions[index].hip, 'female hips are wider for the same build');
    assert(shape.waist/shape.hip < maleProportions[index].waist/maleProportions[index].hip, 'female waist-to-hip ratio remains distinct');
  });
  await page.getByRole('button',{name:'Change avatar',exact:true}).click();
  assert.equal(await picker.locator('.animal-avatar[data-gender="female"]').count(),2);
  await checkPlainPicker();
  await picker.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.getByRole('button',{name:'Step 2: About you',exact:true}).click();
  await page.getByRole('button',{name:/^Male/}).click();
  assert.deepEqual(await page.locator('.body-choices .animal-torso').evaluateAll(es=>es.map(e=>e.getAttribute('d'))),malePaths, 'returning to Male restores the original outlines');
  assert.equal(await page.locator('.body-choices svg image').count(),0);
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
  await page.screenshot({path:'/tmp/go-selkirk-body-types.png',fullPage:true});
  await page.getByRole('button',{name:'Change avatar',exact:true}).click();
  await picker.getByRole('button',{name:'Select Shiba Inu',exact:true}).click();
  await picker.getByRole('button',{name:'Cancel',exact:true}).click();
  assert.equal(await page.locator('.body-choices .animal-avatar[data-species="selkirk"]').count(),3);
  await page.getByRole('button',{name:'Change avatar',exact:true}).click();
  await picker.getByRole('button',{name:'Select Shiba Inu',exact:true}).click();
  await picker.getByRole('button',{name:'Use this avatar',exact:true}).click();
  assert.equal(await page.locator('.body-choices .animal-avatar[data-species="shiba"]').count(),3);
  await checkBuildMuscles();
  await checkMaleLeanImage(page.locator('.body-choices'));
  assert.equal(await page.locator('.body-choices svg.animal-avatar[data-species="shiba"]').count(),2, 'Athletic and Strong retain their vector models');
  const shibaMalePaths = await page.locator('.body-choices svg.animal-avatar').evaluateAll(es=>Object.fromEntries(es.map(e=>[e.dataset.build,e.querySelector('.animal-torso').getAttribute('d')])));
  await page.getByRole('button',{name:'Step 2: About you',exact:true}).click();
  await page.getByRole('button',{name:/^Female/}).click();
  assert.equal(await page.locator('.body-choices .animal-avatar[data-species="shiba"][data-gender="female"]').count(),3);
  await checkBuildMuscles();
  assert.equal(await page.locator('.body-choices svg.animal-avatar[data-build="lean"]').count(),1, 'Female Lean keeps its original vector model');
  assert.equal(await page.locator('.body-choices img.animal-avatar-uploaded').count(),0, 'the new image never replaces female variants');
  const shibaFemalePaths = await page.locator('.body-choices svg.animal-avatar').evaluateAll(es=>Object.fromEntries(es.map(e=>[e.dataset.build,e.querySelector('.animal-torso').getAttribute('d')])));
  for (const build of ['athletic','strong']) assert.notEqual(shibaFemalePaths[build],shibaMalePaths[build], `${build} preserves distinct gender silhouettes`);
  await page.getByRole('button',{name:'Step 2: About you',exact:true}).click();
  await page.getByRole('button',{name:/^Male/}).click();
  await checkMaleLeanImage(page.locator('.body-choices'));
  assert.deepEqual(await page.locator('.body-choices svg.animal-avatar').evaluateAll(es=>Object.fromEntries(es.map(e=>[e.dataset.build,e.querySelector('.animal-torso').getAttribute('d')]))),shibaMalePaths);

  await page.getByRole('button',{name:'Change avatar',exact:true}).click();
  await page.screenshot({path:'/tmp/go-animal-avatar-picker.png',fullPage:true});
  await page.keyboard.press('Escape');
  assert.equal(await page.getByRole('dialog').count(),0);
  await page.getByRole('button',{name:/^Strong/}).click();
  assert.equal(await page.locator('.character-summary svg.animal-avatar[data-species="shiba"][data-build="strong"]').count(),1);
  await page.getByRole('button',{name:'Step 3: Body type',exact:true}).click();
  await page.getByRole('button',{name:'Lean',exact:true}).click();
  await checkMaleLeanImage(page.locator('.character-summary'));
  await page.getByRole('button',{name:'Save your profile and go to training',exact:true}).click();
  await page.reload();
  await page.locator('#go-intro').waitFor({state:'detached'});
  await page.getByText('Build muscle',{exact:true}).click();
  await page.getByRole('button',{name:/Select your avatar/}).click();
  assert.equal(await picker.getByRole('button',{name:'Select Shiba Inu',exact:true}).getAttribute('aria-pressed'),'true');
  await checkPlainPicker();
  await picker.getByRole('button',{name:'Cancel',exact:true}).click();
  await page.getByRole('button',{name:/^Male/}).click();
  await checkMaleLeanImage(page.locator('.body-choices'));
  assert.equal(await page.getByRole('button',{name:'Lean',exact:true}).getAttribute('aria-pressed'),'true', 'the selected Male Lean image survives save and reload');
  await page.getByRole('button',{name:'Step 2: About you',exact:true}).click();
  await page.getByRole('button',{name:'Select your avatar',exact:true}).click();
  await picker.getByRole('button',{name:'Select Selkirk Rex',exact:true}).click();
  await picker.getByRole('button',{name:'Use this avatar',exact:true}).click();
  await page.getByRole('button',{name:/^Female/}).click();
  await page.getByRole('button',{name:/^Athletic/}).click();
  assert.equal(await page.locator('.character-summary .animal-avatar[data-gender="female"]').count(),1);
  await page.getByRole('button',{name:'Save your profile and go to training',exact:true}).click();
  await page.reload();
  await page.locator('#go-intro').waitFor({state:'detached'});
  await page.getByText('Build muscle',{exact:true}).click();
  assert.equal(await page.getByRole('button',{name:/^Female/}).getAttribute('aria-pressed'),'true');
  await page.getByRole('button',{name:/^Female/}).click();
  assert.equal(await page.locator('.body-choices .animal-avatar[data-species="selkirk"][data-gender="female"]').count(),3);

  // Profile photos remain separate from full-body training characters.
  await page.getByRole('button',{name:'Profile settings',exact:true}).click();
  const settings = page.getByRole('dialog').filter({has:page.getByRole('heading',{name:'Your goals. Your way.',exact:true})});
  const positions = await settings.locator('.settings-avatar-section, input[name="name"]').evaluateAll(es => es.map(e=>e.getBoundingClientRect().top));
  assert(positions[0] < positions[1], 'upload belongs above Your name');
  await settings.getByRole('button',{name:'Upload profile photo',exact:true}).click();
  const editor = page.getByRole('dialog',{name:'Create your own avatar?',exact:true});
  assert.equal(await editor.getByRole('button',{name:'Use this avatar',exact:true}).isDisabled(),true);
  await editor.getByLabel('Upload avatar photo').setInputFiles({name:'bad.txt',mimeType:'text/plain',buffer:Buffer.from('bad')});
  assert.match(await editor.getByRole('alert').textContent(),/Choose a JPG/);
  await editor.getByLabel('Upload avatar photo').setInputFiles({name:'broken.png',mimeType:'image/png',buffer:Buffer.from('broken')});
  await editor.getByRole('alert').filter({hasText:'couldn’t open'}).waitFor();
  await editor.getByLabel('Upload avatar photo').setInputFiles('public/cat-coach/portrait.png');
  await editor.locator('canvas').waitFor();
  const first = await editor.locator('canvas').evaluate(c=>c.toDataURL());
  await editor.getByLabel('Zoom',{exact:true}).fill('1.5');
  await editor.getByLabel('Vertical position',{exact:true}).fill('25');
  assert.notEqual(await editor.locator('canvas').evaluate(c=>c.toDataURL()),first);
  await editor.getByRole('button',{name:'Use this avatar',exact:true}).click();
  await settings.getByRole('button',{name:'Save preferences',exact:true}).click();
  assert.equal(await page.locator('button[aria-label="Profile settings"] img').count(),1);
  assert.equal(await page.locator('.body-choices svg image').count(),0);
  assert.equal(await page.locator('.body-choices .animal-avatar[data-species="selkirk"]').count(),3);
  await page.getByRole('button',{name:'Open navigation',exact:true}).click();
  assert.equal(await page.locator('.profile-button .avatar img').count(),1);
  await page.locator('.profile-button').click();
  await settings.getByRole('button',{name:'Change profile photo',exact:true}).click();
  await page.keyboard.press('Escape');
  assert.equal(await settings.count(),1);
  await settings.getByRole('button',{name:'Remove profile photo',exact:true}).click();
  await settings.getByRole('button',{name:'Save preferences',exact:true}).click();
  assert.equal(await page.locator('button[aria-label="Profile settings"] img').count(),0);
  await page.getByRole('button',{name:'Profile settings',exact:true}).click();
  await settings.getByRole('button',{name:'Upload profile photo',exact:true}).click();
  await editor.getByLabel('Upload avatar photo').setInputFiles('public/cat-coach/portrait.png');
  await editor.locator('canvas').waitFor();
  await editor.getByRole('button',{name:'Use this avatar',exact:true}).click();
  await settings.getByRole('button',{name:'Save preferences',exact:true}).click();
  await page.reload();
  await page.locator('#go-intro').waitFor({state:'detached'});
  for (const width of [390, 1440]) {
    await page.setViewportSize({width, height:900});
    const geometry = await page.locator('button[aria-label="Profile settings"]').evaluate(button => {
      const image = button.querySelector('img');
      const box = button.getBoundingClientRect(), photo = image.getBoundingClientRect();
      return {width:box.width, height:box.height, imageWidth:photo.width, imageHeight:photo.height, padding:getComputedStyle(button).padding, overflow:getComputedStyle(button).overflow};
    });
    assert.equal(geometry.width, geometry.height, `profile button must stay square at ${width}px`);
    assert.equal(geometry.imageWidth, geometry.imageHeight, `uploaded photo must stay square at ${width}px`);
    assert.equal(geometry.padding, '0px', 'native button padding must not squeeze the image');
    assert.equal(geometry.overflow, 'hidden', 'photo is clipped by the circular frame');
  }
  assert.deepEqual(errors, []);
  console.log('PASS supplied Male Shiba Lean image loads in cards and summary, persists after save/reload and stays scoped away from female/other builds/plain picker; full-body Shiba/Selkirk selection, plain picker avatars, Athletic/Strong chest contours with unchanged Lean, distinct male/female silhouettes and restored Male shapes, build variants, gender persistence, cancel/Escape, mobile layout; separate profile upload/crop/removal and round header/sidebar photos');
})().catch(error => { console.error(error); process.exitCode = 1; }).finally(async () => { await browser?.close(); });
